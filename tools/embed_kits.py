#!/usr/bin/env python3
"""embed_kits.py <out.inc> <kit file>...: writes each 16 KB .kit file as a C array kBuiltinKitData0, kBuiltinKitData1, ... (src/gb/builtin_kits.cpp includes the result)."""
import sys

def main():
    out, files = sys.argv[1], sys.argv[2:]
    with open(out, 'w') as f:
        f.write('// Generated by tools/embed_kits.py from demos/kits; do not edit.\n')
        for n, path in enumerate(files):
            data = open(path, 'rb').read()
            if len(data) != 0x4000:
                sys.exit('%s: a kit is 16384 bytes' % path)
            f.write('static const uint8_t kBuiltinKitData%d[0x4000] = {\n' % n)
            for i in range(0, len(data), 24):
                f.write(','.join(str(b) for b in data[i:i + 24]) + ',\n')
            f.write('};\n')

main()
