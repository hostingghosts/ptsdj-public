"""assets/boot_chime.wav (24-bit stereo) -> src/atw/chime_pcm.h: mono 16-bit samples for the power-on sound."""
import sys, wave

src = sys.argv[1] if len(sys.argv) > 1 else "assets/boot_chime.wav"
dst = sys.argv[2] if len(sys.argv) > 2 else "src/atw/chime_pcm.h"
w = wave.open(src)
n, ch, width, rate = w.getnframes(), w.getnchannels(), w.getsampwidth(), w.getframerate()
raw = w.readframes(n)
step = ch * width
samples = []
diff = 0
for i in range(n):
    f = raw[i * step:(i + 1) * step]
    v = [int.from_bytes(f[c * width:(c + 1) * width], "little", signed=True) >> (8 * (width - 2)) for c in range(ch)]
    diff = max(diff, abs(v[0] - v[-1]))
    samples.append(v[0])
with open(dst, "w") as o:
    o.write("// Generated by tools/make_chime.py from assets/boot_chime.wav: the power-on sound, %d samples at %d Hz (mono, 16-bit).\n" % (n, rate))
    o.write("#pragma once\n#include <cstdint>\n\nnamespace atw {\ninline constexpr int kChimeRate = %d;\ninline constexpr int kChimeLen = %d;\n" % (rate, n))
    o.write("inline constexpr int16_t kChimePcm[kChimeLen] = {\n")
    for i in range(0, n, 16):
        o.write(",".join(str(x) for x in samples[i:i + 16]) + ",\n")
    o.write("};\n}  // namespace atw\n")
print(n, rate, "max L-R difference", diff, "peak", max(abs(x) for x in samples))
