"""Emit core/gb/defaults.inc: RLE of a fresh LSDJ working song (0x8000 bytes), from the oracle (base0.sav)."""
import sys
d = open(sys.argv[1], 'rb').read()[:0x8000]
out, i = [], 0
while i < len(d):
    j = i
    while j < len(d) and d[j] == d[i] and j - i < 255: j += 1
    out.append((j - i, d[i])); i = j
print('// generated by tools/gen_defaults.py: {count, value} runs of a fresh LSDJ 9.4.2 song')
print(', '.join('{%d,%d}' % o for o in out))
