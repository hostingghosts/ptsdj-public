#include <cstring>
#include <initializer_list>

#include "gb/player.h"

namespace gb {

namespace {

constexpr double kPi = 3.14159265358979323846;

// LSDJ note numbers: 1 = C2, 13 = C3, 34 = A4.
constexpr int N(int octave, int semitone) { return 1 + (octave - 2) * 12 + semitone; }
enum { C = 0, Cs, D, Ds, E, F, Fs, G, Gs, A, As, B };

// The chord progression Am - F - C - G is one phrase played at four transposes from A (0, -4, +3, -2), so every
// phrase that follows the chords is written once in A and once more for the major chords' third.
constexpr int8_t kChordTrans[4] = {0, -4, 3, -2};

struct Step { int at, note, instr; int cmd = 0, val = 0; };

class Writer {
public:
    explicit Writer(Song& s) : s_(s) { s_.reset(); }

    int instrument(const char* name, std::initializer_list<uint8_t> bytes) {
        const int i = ni_++;
        uint8_t* in = s_.instrument(i);
        std::memset(in, 0, 16);
        int k = 0;
        for (uint8_t b : bytes) in[k++] = b;
        s_.markInstrument(i);
        std::memset(s_.mem() + off::kInstrNames + i * 5, 0, 5);
        std::memcpy(s_.mem() + off::kInstrNames + i * 5, name, std::strlen(name));
        return i;
    }

    int phrase(std::initializer_list<Step> steps) {
        const int p = np_++;
        for (const Step& st : steps) {
            s_.note(p, st.at) = uint8_t(st.note);
            s_.phraseInstr(p, st.at) = uint8_t(st.instr);
            s_.phraseCmd(p, st.at) = uint8_t(st.cmd);
            s_.phraseVal(p, st.at) = uint8_t(st.val);
        }
        s_.markPhrase(p);
        return p;
    }

    int chain(std::initializer_list<int> phrases, bool chords = false) {
        const int c = nc_++;
        int k = 0;
        for (int p : phrases) {
            s_.chainPhrase(c, k) = uint8_t(p);
            s_.chainTrans(c, k) = chords ? uint8_t(kChordTrans[k & 3]) : 0;
            ++k;
        }
        s_.markChain(c);
        return c;
    }

    void row(int r, int pu1, int pu2, int wav, int noi) {
        s_.songCell(r, 0) = uint8_t(pu1);
        s_.songCell(r, 1) = uint8_t(pu2);
        s_.songCell(r, 2) = uint8_t(wav);
        s_.songCell(r, 3) = uint8_t(noi);
    }

    // A wave drawn into every frame of a synth, so nothing has to be generated by the LSDJ ROM; the synth is marked hand drawn.
    void wave(int synth, double h2, double h3) {
        uint8_t* f = s_.wave(synth * 16);
        std::memset(f, 0, 16);
        for (int i = 0; i < 32; ++i) {
            const double x = 2 * kPi * i / 32;
            const double v = (std::sin(x) + h2 * std::sin(2 * x) + h3 * std::sin(3 * x)) / (1 + h2 + h3);
            int q = int(std::lround(7.5 + 7.0 * v));
            q = q < 0 ? 0 : q > 15 ? 15 : q;
            f[i / 2] = uint8_t(f[i / 2] | (i & 1 ? q : q << 4));
        }
        for (int k = 1; k < 16; ++k) std::memcpy(s_.wave(synth * 16 + k), f, 16);
        s_.at(off::kHandDrawn + 1) = uint8_t(s_.at(off::kHandDrawn + 1) | (1u << synth));
    }

    void tableRow(int table, int row, int transpose) { s_.at(off::kTblTrans + table * 16 + row) = uint8_t(int8_t(transpose)); }

    void project() {
        s_.at(off::kTempo) = uint8_t(kDemoTempo);
        s_.at(off::kSync) = 1;                       // with SYNC on in both songs, Play on either console starts both
    }

private:
    Song& s_;
    int ni_ = 0, np_ = 0, nc_ = 0;
};

// Instrument bytes (see docs/LSDJ_FORMAT.md): pulse {0, envelope, pu2 tune, length, sweep (FF = none), 0, table (20 | n), duty and pan, 0, stage 2,
// 0xD0, 0, 0, 0, 0xF3, 0}; the envelope byte is start level and rate, stage 2 holds the level it settles at (rate 0 = hold).
constexpr uint8_t kDuty50 = 0x83, kDuty25 = 0x43;

}  // namespace

void buildDemoA(Song& s) {
    Writer w(s);
    const int lead = w.instrument("LEAD", {0x00, 0xB4, 0, 0, 0xFF, 0, 0, kDuty50, 0, 0x60, 0xD0, 0, 0, 0, 0xF3, 0});   // 11 falls to 6 and holds: a soft pluck
    const int pad = w.instrument("PAD", {0x00, 0x70, 0, 0, 0xFF, 0, 0, kDuty25, 0, 0, 0xD0, 0, 0, 0, 0xF3, 0});         // level 7, held
    const int bell = w.instrument("BELL", {0x01, 0x40, 0x0F, 0x00, 0xFF, 0, 0x20, 0x03, 0, 0, 0, 0, 0, 0, 0, 0});        // synth 0, volume 2, table 0
    w.wave(0, 0.0, 0.0);                                                                                                 // a plain sine
    w.tableRow(0, 0, 12);                                                                                                // the bell's table: one tick an octave up, then the note itself

    const int sil = w.phrase({});
    // Verse: quarter notes, the notes on beats 1 and 3 belong to the chord of the bar (Am F C G).
    const int v1 = w.phrase({{0, N(4, A), lead}, {4, N(5, C), lead}, {8, N(5, E), lead}, {12, N(5, D), lead}});
    const int v2 = w.phrase({{0, N(5, C), lead}, {4, N(4, A), lead}, {8, N(4, A), lead}, {12, N(4, G), lead}});
    const int v3 = w.phrase({{0, N(5, E), lead}, {4, N(5, D), lead}, {8, N(5, C), lead}, {12, N(5, E), lead}});
    const int v4 = w.phrase({{0, N(5, D), lead}, {4, N(4, B), lead}, {8, N(5, D), lead}, {12, N(4, B), lead, kCmdK, 0x12}});   // K ends the last note before the bar does
    // Chorus: the same bars in eighth notes, a little higher.
    const int c1 = w.phrase({{0, N(5, E), lead}, {2, N(5, D), lead}, {4, N(5, C), lead}, {6, N(5, D), lead}, {8, N(5, E), lead}, {12, N(5, C), lead}});
    const int c2 = w.phrase({{0, N(5, C), lead}, {2, N(4, A), lead}, {4, N(5, C), lead}, {6, N(5, E), lead}, {8, N(5, F), lead}, {12, N(5, E), lead}});
    const int c3 = w.phrase({{0, N(5, E), lead}, {2, N(5, G), lead}, {4, N(5, E), lead}, {6, N(5, C), lead}, {8, N(5, C), lead}, {12, N(5, E), lead}});
    const int c4 = w.phrase({{0, N(5, D), lead}, {2, N(4, B), lead}, {4, N(4, G), lead}, {6, N(4, B), lead}, {8, N(5, D), lead}, {12, N(4, B), lead}});
    // Pad: the chord's root twice a bar with the chord command (C 37 = minor, C 47 = major), written in A and moved by the chain's transposes.
    const int padM = w.phrase({{0, N(3, A), pad, kCmdC, 0x37}, {8, N(3, A), pad, kCmdC, 0x37}});
    const int padJ = w.phrase({{0, N(3, A), pad, kCmdC, 0x47}, {8, N(3, A), pad, kCmdC, 0x47}});
    // Bell: root, third, fifth, third up the chord (the wave channel sounds an octave below a pulse for the same note number, so these are written
    // an octave higher than they sound). The last note of each bar ends with K: a wave note rings until the next one, even through a quiet section.
    const int belM = w.phrase({{0, N(5, A), bell}, {4, N(6, C), bell}, {8, N(6, E), bell}, {12, N(6, C), bell, kCmdK, 0x12}});
    const int belJ = w.phrase({{0, N(5, A), bell}, {4, N(6, Cs), bell}, {8, N(6, E), bell}, {12, N(6, Cs), bell, kCmdK, 0x12}});

    const int quiet = w.chain({sil, sil, sil, sil});
    const int verse = w.chain({v1, v2, v3, v4});
    const int chorus = w.chain({c1, c2, c3, c4});
    const int chords = w.chain({padM, padJ, padJ, padJ}, true);
    const int bells = w.chain({belM, belJ, belJ, belJ}, true);

    w.row(0, quiet, chords, quiet, quiet);      // intro
    w.row(1, verse, chords, quiet, quiet);      // verse
    w.row(2, chorus, chords, bells, quiet);     // chorus
    w.row(3, verse, chords, bells, quiet);      // verse 2
    w.project();
}

void buildDemoB(Song& s) {
    Writer w(s);
    const int kick = w.instrument("KICK", {0x00, 0xC4, 0, 0, 0xFF, 0, 0x20, kDuty50, 0, 0, 0xD0, 0, 0, 0, 0xF3, 0});      // table 0 drops the pitch
    const int stab = w.instrument("STAB", {0x00, 0x95, 0, 0, 0xFF, 0, 0, kDuty25, 0, 0, 0xD0, 0, 0, 0, 0xF3, 0});
    const int bass = w.instrument("BASS", {0x01, 0x40, 0x0F, 0x10, 0xFF, 0, 0, 0x03, 0, 0, 0, 0, 0, 0, 0, 0});            // synth 1, volume 2
    const int hat = w.instrument("HAT", {0x03, 0x63, 0, 0, 0xFF, 0, 0, 0x03, 0, 0, 0xD0, 0, 0, 0, 0xF3, 0});
    const int snare = w.instrument("SNARE", {0x03, 0xA5, 0, 0, 0xFF, 0, 0, 0x03, 0, 0, 0xD0, 0, 0, 0, 0xF3, 0});
    w.wave(1, 0.35, 0.0);                                                                                                   // sine with some second harmonic
    // The kick's table: one row per tick, A4 down to A2 through Am chord tones (A E C A E C A), then it stays.
    {
        const int rows[7] = {24, 19, 15, 12, 7, 3, 0};
        for (int r = 0; r < 7; ++r) w.tableRow(0, r, rows[r]);
    }
    constexpr int KICK_NOTE = N(2, A), HAT_NOTE = 49, SNARE_NOTE = 41;

    const int sil = w.phrase({});
    const int kA = w.phrase({{0, KICK_NOTE, kick}, {8, KICK_NOTE, kick}});
    const int kB = w.phrase({{0, KICK_NOTE, kick}, {4, KICK_NOTE, kick}, {8, KICK_NOTE, kick}, {12, KICK_NOTE, kick}});
    const int kC = w.phrase({{0, KICK_NOTE, kick}, {4, KICK_NOTE, kick}, {8, KICK_NOTE, kick}, {10, KICK_NOTE, kick}, {12, KICK_NOTE, kick}});
    const int kF = w.phrase({{0, KICK_NOTE, kick}, {4, KICK_NOTE, kick}, {8, KICK_NOTE, kick}, {12, KICK_NOTE, kick}, {14, KICK_NOTE, kick}});
    // Off-beat chord stabs (steps 6 and 14), staccato.
    const int stM = w.phrase({{6, N(3, A), stab, kCmdC, 0x37}, {14, N(3, A), stab, kCmdC, 0x37}});
    const int stJ = w.phrase({{6, N(3, A), stab, kCmdC, 0x47}, {14, N(3, A), stab, kCmdC, 0x47}});
    // Bass: root, octave and fifth only, so it fits every chord of the progression (sounding at A2, 110 Hz, from the wave channel).
    const int bs = w.phrase({{0, N(3, A), bass}, {3, N(3, A), bass}, {6, N(4, A), bass}, {8, N(3, A), bass}, {11, N(4, E), bass}, {14, N(4, A), bass, kCmdK, 0x0A}});
    // Hats and snare on the noise channel.
    const int nA = w.phrase({{0, HAT_NOTE, hat}, {4, HAT_NOTE, hat}, {8, HAT_NOTE, hat}, {12, HAT_NOTE, hat}});
    const int nB = w.phrase({{0, HAT_NOTE, hat}, {2, HAT_NOTE, hat}, {4, SNARE_NOTE, snare}, {6, HAT_NOTE, hat}, {8, HAT_NOTE, hat},
                             {10, HAT_NOTE, hat}, {12, SNARE_NOTE, snare}, {14, HAT_NOTE, hat}});
    const int nC = w.phrase({{0, HAT_NOTE, hat}, {2, HAT_NOTE, hat}, {4, SNARE_NOTE, snare}, {6, HAT_NOTE, hat}, {8, HAT_NOTE, hat},
                             {10, HAT_NOTE, hat}, {12, SNARE_NOTE, snare}, {14, HAT_NOTE, hat}, {15, HAT_NOTE, hat}});
    const int nF = w.phrase({{0, HAT_NOTE, hat}, {2, HAT_NOTE, hat}, {4, SNARE_NOTE, snare}, {6, HAT_NOTE, hat}, {8, SNARE_NOTE, snare},
                             {10, SNARE_NOTE, snare}, {12, SNARE_NOTE, snare}, {13, SNARE_NOTE, snare}, {14, SNARE_NOTE, snare}, {15, SNARE_NOTE, snare}});

    const int quiet = w.chain({sil, sil, sil, sil});
    const int kIntro = w.chain({kA, kA, kA, kA});
    const int kMain = w.chain({kB, kB, kB, kC});
    const int kEnd = w.chain({kB, kB, kB, kF});
    const int stabs = w.chain({stM, stJ, stJ, stJ}, true);
    const int basses = w.chain({bs, bs, bs, bs}, true);
    const int nIntro = w.chain({nA, nA, nA, nA});
    const int nMain = w.chain({nB, nB, nB, nB});
    const int nChorus = w.chain({nC, nC, nC, nC});
    const int nEnd = w.chain({nB, nB, nB, nF});

    w.row(0, kIntro, quiet, quiet, nIntro);      // intro
    w.row(1, kMain, quiet, basses, nMain);       // verse
    w.row(2, kMain, stabs, basses, nChorus);     // chorus
    w.row(3, kEnd, stabs, basses, nEnd);         // verse 2, ending in a fill
    w.project();
}

}  // namespace gb
